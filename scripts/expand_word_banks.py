def parse_words(path: Path) -> list[str]:
    return re.findall(r'"([A-Z0-9_]+)"', path.read_text())


def normalize_additions(raw: str) -> list[str]:
    return [word.strip().upper() for word in raw.split() if word.strip()]


def rewrite_theme(theme: str, additions: list[str]) -> tuple[int, int]:
    path = PUZZLES / f"{theme}.rs"
    existing = parse_words(path)
    merged = []
    seen = set()
    for word in existing + additions:
        if word and word not in seen:
            seen.add(word)
            merged.append(word)
    body = ",\n".join(f'    "{word}"' for word in merged)
    path.write_text(f"pub const WORDS: &[&str] = &[\n{body},\n];\n")
    return len(existing), len(merged)


